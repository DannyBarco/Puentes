// Run against the local server; see USO.md for external test dependency setup.
import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {analyze} from '../beam.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const out=process.env.TEST_ARTIFACTS||'/tmp/puentes-review';
await mkdir(out,{recursive:true});
const field=(i,key)=>page.locator(`#loads [data-i="${i}"][data-key="${key}"]`);
const edit=async(locator,value)=>{await locator.fill(String(value));await locator.press('Tab');};
const calculate=async()=>{await page.locator('#calculate').click();assert.equal(await page.locator('#error').textContent(),'');};
const table=()=>page.locator('#output tr').evaluateAll(rows=>rows.map(r=>[...r.cells].map(c=>Number(c.textContent))));
const close=(a,b)=>assert.ok(Math.abs(a-b)<=.000501,`${a} ≠ ${b}`);
const checkTable=async(model)=>{
  const actual=await table(),expected=analyze(model).envelope;
  assert.equal(actual.length,expected.length);
  actual.forEach((row,i)=>['a','vmin','vmax','mmin','mmax'].forEach((key,j)=>close(row[j],expected[i][key])));
};
try{
  await page.goto(process.env.TEST_URL||'http://127.0.0.1:8000/');
  await page.waitForSelector('#output tr');
  await checkTable({L:10,dx:.1,da:.5,loads:[{p:10,x:0},{p:15,x:-2},{p:10,x:-4}]});
  assert.equal(await page.locator('.chart').count(),4);
  const before=await page.locator('#shear polyline').first().getAttribute('points');
  await edit(field(0,'p'),20);
  assert.equal(await page.locator('#csv').isDisabled(),true);
  await calculate();
  assert.notEqual(await page.locator('#shear polyline').first().getAttribute('points'),before);
  await checkTable({L:10,dx:.1,da:.5,loads:[{p:20,x:0},{p:15,x:-2},{p:10,x:-4}]});
  await edit(field(1,'gap'),3);
  assert.equal(await field(1,'x').inputValue(),'-3');assert.equal(await field(2,'x').inputValue(),'-5');
  await calculate();
  await checkTable({L:10,dx:.1,da:.5,loads:[{p:20,x:0},{p:15,x:-3},{p:10,x:-5}]});
  // A temporary empty or negative gap must not corrupt later positions.
  await edit(field(1,'gap'),'');await page.locator('#calculate').click();
  assert.match(await page.locator('#error').textContent(),/tabla/);
  assert.equal(await field(2,'x').inputValue(),'-5');
  await edit(field(1,'gap'),-1);await page.locator('#calculate').click();
  assert.match(await page.locator('#error').textContent(),/tabla/);
  await edit(field(1,'gap'),2);await calculate();
  assert.equal(await field(2,'x').inputValue(),'-4');
  await page.locator('#mode').selectOption('x');
  await edit(field(1,'x'),-1);await calculate();
  assert.equal(await field(1,'gap').inputValue(),'1');assert.equal(await field(2,'gap').inputValue(),'3');
  await edit(field(1,'x'),1);await page.locator('#calculate').click();
  assert.match(await page.locator('#error').textContent(),/primera carga/);
  await edit(field(1,'x'),-1);await calculate();
  await page.locator('#add').click();assert.equal(await page.locator('#loads tr').count(),4);
  await page.getByRole('button',{name:'Eliminar carga 4',exact:true}).click();await calculate();
  await edit(page.locator('#length'),12);await edit(page.locator('#dx'),.3);await edit(page.locator('#da'),1);
  await calculate();
  const model={L:12,dx:.3,da:1,loads:[{p:20,x:0},{p:15,x:-1},{p:10,x:-4}]};
  await checkTable(model);
  const moment=await page.locator('#moment polyline').getAttribute('points');
  await page.locator('#section').fill('4');
  assert.notEqual(await page.locator('#moment polyline').getAttribute('points'),moment);
  await page.locator('#section').fill('13');
  assert.equal(await page.locator('#moment svg').count(),0);
  await page.locator('#section').fill('4');assert.equal(await page.locator('#moment svg').count(),1);
  await page.locator('#advance').evaluate(el=>{el.value=el.max;el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.match(await page.locator('#advanceText').textContent(),/descargada/);
  assert.equal(await page.locator('#beam text').count(),2);
  const downloadPromise=page.waitForEvent('download');await page.locator('#csv').click();
  const download=await downloadPromise;assert.equal(download.suggestedFilename(),'envolventes.csv');
  await download.saveAs(`${out}/envolventes.csv`);
  const csv=(await readFile(`${out}/envolventes.csv`,'utf8')).trim().split('\n');
  assert.equal(csv[0],'a_m,Vmin_kN,Vmax_kN,Mmin_kNm,Mmax_kNm');
  const expected=analyze(model).envelope;
  assert.equal(csv.length,expected.length+1);
  csv.slice(1).forEach((line,i)=>line.split(',').forEach((v,j)=>assert.equal(Number(v),expected[i][['a','vmin','vmax','mmin','mmax'][j]])));
  // Document the default model in both layouts.
  await page.reload();await page.waitForSelector('#output tr');
  await page.screenshot({path:`${out}/desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:`${out}/mobile.png`,fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.setViewportSize({width:320,height:700});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  console.log('PASS Chromium: edición P/x/separaciones; recuperación de errores; añadir/eliminar; L/Δx/ΔL; 4 gráficas; tabla numérica; sección; descarga CSV íntegra; estado descargado; escritorio y móvil sin desbordamiento.');
  console.log(`Capturas y CSV: ${out}`);
}finally{await browser.close();}
